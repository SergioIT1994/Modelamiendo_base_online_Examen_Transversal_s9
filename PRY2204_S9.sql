SELECT 'ID:' || a.id_asociacion || ' * ' || a.nombre AS "ASOCIACION", TO_CHAR(a.fecha_creacion, 'DD-MM-YYYY') AS "CREADA", a.tipo_asociacion AS "TIPO" FROM ASOCIACION a WHERE a.tipo_asociacion = 'P' AND a.fecha_creacion > DATE '2000-12-31' ORDER BY a.fecha_creacion DESC;


